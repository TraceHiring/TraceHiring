/** The only branches that may be `unreachable` (§8.5, MT-11 day-one check). */
export const UNREACHABLE_ALLOWED = Object.freeze({
  'MT-11': Object.freeze(['insert_without_check', 'select_delete_without_using']),
});

const ID_RE = /^MT-\d+[a-z]?$/;
const BRANCH_RE = /^[a-z0-9_]+$/;
const REGEN = 'run node scripts/gen-catalog-tests.mjs';
const TX_CONTROL = new Set(['begin', 'commit', 'rollback', 'savepoint', 'release', 'end', 'abort']);

const toLf = (s) => s.replace(/\r\n/g, '\n');
const fixtureName = (id, branch) => `${id}.${branch}.violation.sql`;
const isPlainObject = (v) => typeof v === 'object' && v !== null && !Array.isArray(v);
const hasExactKeys = (o, keys) =>
  Object.keys(o).length === keys.length && keys.every((k) => Object.hasOwn(o, k));

/**
 * Validates the manifest's shape and the `unreachable` rules.
 * @returns {{ checks: {id: string, branches: {id: string, unreachable: string|null}[]}[] | null,
 *             problems: string[] }} `checks` is null when the shape is unusable.
 */
export function validateManifest(value) {
  const problems = [];
  if (!isPlainObject(value)) return { checks: null, problems: ['must be a JSON object'] };
  if (!Array.isArray(value.checks)) {
    return { checks: null, problems: ['`checks` must be an array'] };
  }
  const checks = [];
  const ids = new Set();
  let shapeOk = true;
  value.checks.forEach((entry, i) => {
    const where = `checks[${i}]`;
    if (!isPlainObject(entry)) {
      problems.push(`${where} must be an object {id, branches}`);
      shapeOk = false;
      return;
    }
    const id = entry.id;
    const label = typeof id === 'string' ? id : where;
    if (typeof id !== 'string' || !ID_RE.test(id)) {
      problems.push(`${where}: id ${JSON.stringify(id)} must match ${ID_RE}`);
      shapeOk = false;
    } else if (ids.has(id)) {
      problems.push(`${id}: duplicate check id`);
      shapeOk = false;
    } else ids.add(id);
    if (!hasExactKeys(entry, ['id', 'branches'])) {
      problems.push(`${label}: a check has exactly the keys id and branches`);
      shapeOk = false;
    }
    if (!Array.isArray(entry.branches) || entry.branches.length === 0) {
      problems.push(`${label}: branches must be a non-empty array`);
      shapeOk = false;
      return;
    }
    const branches = [];
    const seen = new Set();
    entry.branches.forEach((b, j) => {
      let bid;
      let marked = false;
      let unreachable = null;
      if (typeof b === 'string') bid = b;
      else if (isPlainObject(b) && hasExactKeys(b, ['id', 'unreachable'])) {
        bid = b.id;
        marked = true;
        unreachable = b.unreachable;
      } else {
        problems.push(
          `${label}: branch ${j} must be a string or an object exactly {id, unreachable}`,
        );
        shapeOk = false;
        return;
      }
      if (typeof bid !== 'string' || !BRANCH_RE.test(bid)) {
        problems.push(`${label}: branch id ${JSON.stringify(bid)} must match ${BRANCH_RE}`);
        shapeOk = false;
        return;
      }
      if (seen.has(bid)) {
        problems.push(`${label}.${bid}: duplicate branch`);
        shapeOk = false;
        return;
      }
      seen.add(bid);
      if (marked) {
        if (!(UNREACHABLE_ALLOWED[id] ?? []).includes(bid)) {
          problems.push(
            `${label}.${bid}: unreachable is allowed only on ${Object.entries(UNREACHABLE_ALLOWED)
              .flatMap(([c, bs]) => bs.map((x) => `${c}.${x}`))
              .join(' and ')} (§8.5)`,
          );
        } else if (typeof unreachable !== 'string' || !/^ERROR:\s*\S/.test(unreachable)) {
          problems.push(
            `${label}.${bid}: unreachable must hold the recorded PostgreSQL error text, starting with "ERROR:"`,
          );
        }
      }
      // A denied `unreachable` is still recorded as unreachable, so nothing generates for it.
      branches.push({ id: bid, unreachable: marked ? String(unreachable) : null });
    });
    checks.push({ id: label, branches });
  });
  return { checks: shapeOk ? checks : null, problems };
}

/**
 * Lexes SQL the way psql splits it into statements: quotes, E'' strings, quoted identifiers,
 * dollar quotes, nested block comments, parentheses and CREATE [OR REPLACE] FUNCTION|PROCEDURE
 * … BEGIN ATOMIC … END bodies (psqlscan.l's begin_depth heuristic).
 * @returns {{ statements: {tokens: string[], terminated: boolean}[], metaCommand: boolean,
 *             unterminated: string | null }}
 */
export function lexSql(text) {
  const statements = [];
  let cur = null;
  let parenDepth = 0;
  let beginDepth = 0;
  let ids = [];
  let metaCommand = false;
  let unterminated = null;
  const n = text.length;
  let i = 0;

  const token = (t) => {
    if (!cur) {
      cur = { tokens: [], terminated: false };
      statements.push(cur);
      parenDepth = 0;
      beginDepth = 0;
      ids = [];
    }
    cur.tokens.push(t);
  };
  const inRoutineDefinition = () =>
    ids[0] === 'create' &&
    (['function', 'procedure'].includes(ids[1]) ||
      (ids[1] === 'or' && ids[2] === 'replace' && ['function', 'procedure'].includes(ids[3])));
  const skipQuoted = (start, quote, backslashEscapes) => {
    let j = start + 1;
    while (j < n) {
      const c = text[j];
      if (backslashEscapes && c === '\\') j += 2;
      else if (c === quote && text[j + 1] === quote) j += 2;
      else if (c === quote) return j + 1;
      else j++;
    }
    unterminated ??= quote === '"' ? 'quoted identifier' : 'string literal';
    return n;
  };

  while (i < n) {
    const c = text[i];
    if (/\s/.test(c)) {
      i++;
    } else if (c === '-' && text[i + 1] === '-') {
      const e = text.indexOf('\n', i);
      i = e === -1 ? n : e + 1;
    } else if (c === '/' && text[i + 1] === '*') {
      let depth = 1;
      let j = i + 2;
      while (j < n && depth > 0) {
        if (text[j] === '/' && text[j + 1] === '*') {
          depth++;
          j += 2;
        } else if (text[j] === '*' && text[j + 1] === '/') {
          depth--;
          j += 2;
        } else j++;
      }
      if (depth > 0) unterminated ??= 'block comment';
      i = j;
    } else if (c === ';') {
      if (cur && parenDepth === 0 && beginDepth === 0) {
        cur.terminated = true;
        cur = null;
      } else if (cur) cur.tokens.push(';');
      i++;
    } else if (c === "'") {
      token("'");
      i = skipQuoted(i, "'", false);
    } else if (c === '"') {
      token('"');
      i = skipQuoted(i, '"', false);
    } else if (c === '$') {
      const m = /\$([A-Za-z_\u0080-￿][A-Za-z0-9_\u0080-￿]*)?\$/y;
      m.lastIndex = i;
      const d = m.exec(text);
      if (d) {
        token('$');
        const close = text.indexOf(d[0], i + d[0].length);
        if (close === -1) {
          unterminated ??= 'dollar-quoted string';
          i = n;
        } else i = close + d[0].length;
      } else {
        token('$');
        i++;
      }
    } else if (c === '\\') {
      metaCommand = true; // psql treats a backslash outside quotes as a meta-command
      token('\\');
      i++;
    } else if (/[A-Za-z_\u0080-￿]/.test(c)) {
      const m = /[A-Za-z_\u0080-￿][A-Za-z0-9_$\u0080-￿]*/y;
      m.lastIndex = i;
      const word = m.exec(text)[0];
      i += word.length;
      const lower = word.toLowerCase();
      if ((lower === 'e' || lower === 'x' || lower === 'b' || lower === 'n') && text[i] === "'") {
        token("'");
        i = skipQuoted(i, "'", lower === 'e');
        continue;
      }
      token(lower);
      ids.push(lower);
      if (parenDepth === 0 && inRoutineDefinition()) {
        if (lower === 'begin') beginDepth++;
        else if (lower === 'case' && beginDepth >= 1) beginDepth++;
        else if (lower === 'end' && beginDepth > 0) beginDepth--;
      }
    } else {
      token(c);
      if (c === '(') parenDepth++;
      else if (c === ')' && parenDepth > 0) parenDepth--;
      i++;
    }
  }
  return { statements, metaCommand, unterminated };
}

/** Problems with a check file's text (README "Rules for a check file", rule 1). */
export function checkFileProblems(text) {
  const problems = [];
  if (text.startsWith('﻿')) problems.push('starts with a UTF-8 BOM');
  const body = embeddedCheck(text);
  if (body === '') problems.push('is empty');
  if (text.includes('$q$')) problems.push('contains $q$ (the generator quotes checks with $q$)');
  if (body.includes(';')) {
    problems.push(
      'contains a ";" other than one optional trailing ";" (README rule 1: one statement, no ";" in comments or strings)',
    );
  }
  return problems;
}

/** Problems with a fixture's text (README "Rules for a fixture"). */
export function fixtureProblems(text) {
  const problems = [];
  if (text.startsWith('﻿')) problems.push('starts with a UTF-8 BOM');
  if (text.includes('$q$')) problems.push('contains $q$');
  const lines = toLf(text).split('\n');
  const metaLines = lines.flatMap((l, k) => (/^\s*\\/.test(l) ? [k + 1] : []));
  const lex = lexSql(toLf(text));
  if (metaLines.length > 0) {
    problems.push(`has a psql meta-command on line ${metaLines.join(', ')}`);
  } else if (lex.metaCommand) {
    problems.push('has a psql meta-command (a backslash outside quotes)');
  }
  if (lex.unterminated) problems.push(`has an unterminated ${lex.unterminated}`);
  for (const s of lex.statements) {
    const [first, second] = s.tokens;
    if (TX_CONTROL.has(first) || (first === 'start' && second === 'transaction')) {
      problems.push(
        `has a transaction control statement (${first}${first === 'start' ? ' transaction' : ''}); the generator wraps each fixture in a savepoint`,
      );
    }
  }
  if (lex.statements.length === 0) problems.push('has no statements');
  else if (!lex.unterminated && !lex.statements.at(-1).terminated) {
    problems.push('does not end with ; (every statement ends with ;)');
  }
  return problems;
}

/** A check's SQL as embedded in the generated file: LF, trimmed, one trailing `;` stripped. */
function embeddedCheck(text) {
  let s = toLf(text).replace(/^﻿/, '').trim();
  if (s.endsWith(';')) s = s.slice(0, -1).trimEnd();
  return s;
}

function listDir(abs) {
  return existsSync(abs) ? readdirSync(abs, { withFileTypes: true }) : [];
}

const SHARED_MARK_RE = /^-- shared:([a-z0-9_]+) (begin|end)\b(.*)$/;
const COPY_MARK_RE = /^-- (MT-\d+[a-z]?) copy (begin|end)\s*$/;
const SAME_TEXT_RE = /^ \(the same text in (.+)\)$/;

/**
 * The `-- <name> begin` … `-- <name> end` blocks in `text` (catalog review D9). `re` captures the
 * name, begin|end and (optionally) the rest of the begin line; `label(name)` names a block in problems.
 * @returns {{ blocks: {name: string, rest: string, body: string}[], problems: string[] }}
 */
export function markedBlocks(text, re, label) {
  const blocks = [];
  const problems = [];
  let open = null;
  toLf(text)
    .split('\n')
    .forEach((line, k) => {
      const m = re.exec(line);
      if (!m) {
        open?.body.push(line);
        return;
      }
      const [, name, kind, rest = ''] = m;
      if (kind === 'begin') {
        if (open) {
          problems.push(
            `${label(open.name)}: begin on line ${open.line} without end (another begin on line ${k + 1})`,
          );
        }
        open = { name, line: k + 1, rest, body: [] };
      } else if (open?.name === name) {
        blocks.push({ name, rest: open.rest, body: open.body.join('\n') });
        open = null;
      } else {
        problems.push(`${label(name)}: end on line ${k + 1} without begin`);
      }
    });
  if (open) problems.push(`${label(open.name)}: begin on line ${open.line} without end`);
  return { blocks, problems };
}

/**
 * Shared blocks (`-- shared:<name> begin (the same text in <IDs>)`) must be byte-identical (after LF)
 * in every check file, and sit in exactly the checks their begin line lists.
 * @param {{ rel: string, id: string, text: string }[]} files check files in manifest order
 */
export function sharedBlockProblems(files) {
  const problems = [];
  const copies = new Map();
  for (const f of files) {
    const { blocks, problems: p } = markedBlocks(f.text, SHARED_MARK_RE, (n) => `shared:${n}`);
    problems.push(...p.map((x) => `${f.rel}: ${x}`));
    for (const b of blocks) {
      if (!copies.has(b.name)) copies.set(b.name, []);
      copies.get(b.name).push({ ...f, rest: b.rest, key: `${b.rest}\n${b.body}` });
    }
  }
  for (const name of [...copies.keys()].sort()) {
    const [first, ...others] = copies.get(name);
    for (const c of others) {
      if (c.key !== first.key) {
        problems.push(
          `${c.rel}: shared:${name} differs from the copy in ${first.rel} (copies must be identical)`,
        );
      }
    }
    const m = SAME_TEXT_RE.exec(first.rest);
    if (!m) {
      problems.push(
        `${first.rel}: shared:${name} begin line must end with "(the same text in <IDs>)"`,
      );
      continue;
    }
    const listed = [...new Set(m[1].split(/,\s*|\s+and\s+/).map((s) => s.trim()))].sort();
    const actual = [...new Set(copies.get(name).map((c) => c.id))].sort();
    if (listed.join() !== actual.join()) {
      problems.push(
        `shared:${name}: the begin line lists ${listed.join(', ')} but the block is in ${actual.join(', ')}`,
      );
    }
  }
  return problems;
}

/**
 * Hand-kept copies of a check in supabase/tests/*.sql (`-- MT-11 copy begin` … `-- MT-11 copy end`, the
 * probe's negative controls) must equal the check as embedded (LF, trimmed, trailing `;` dropped).
 * @param {Map<string, string | null>} sqlById embedded SQL per manifest ID (null when the file is missing)
 */
export function checkCopyProblems(root, sqlById) {
  const problems = [];
  const files = listDir(path.join(root, ...TESTS_DIR.split('/')))
    .filter((d) => d.isFile() && d.name.endsWith('.sql') && `${TESTS_DIR}/${d.name}` !== OUTPUT)
    .map((d) => d.name)
    .sort();
  for (const name of files) {
    const rel = `${TESTS_DIR}/${name}`;
    const { blocks, problems: p } = markedBlocks(
      readRel(root, rel),
      COPY_MARK_RE,
      (n) => `${n} copy`,
    );
    problems.push(...p.map((x) => `${rel}: ${x}`));
    for (const b of blocks) {
      if (!sqlById.has(b.name)) {
        problems.push(`${rel}: ${b.name} copy: no such check in manifest.json`);
      } else if (sqlById.get(b.name) !== null && embeddedCheck(b.body) !== sqlById.get(b.name)) {
        problems.push(
          `${rel}: the ${b.name} copy differs from ${CATALOG_DIR}/${b.name}.sql (keep it identical)`,
        );
      }
    }
  }
  return problems;
}

function readRel(root, rel) {
  return readFileSync(path.join(root, ...rel.split('/')), 'utf8');
}

/**
 * Reads and validates supabase/catalog-checks/ under `root`.
 * @returns {{ catalog: {id, sql, branches: {id, unreachable, fixture}[]}[] | null,
 *             checks: object[] | null, problems: string[] }}
 */
export function loadCatalog(root) {
  const problems = [];
  const abs = (rel) => path.join(root, ...rel.split('/'));
  if (!existsSync(abs(MANIFEST_PATH))) {
    return { catalog: null, checks: null, problems: [`${MANIFEST_PATH}: missing`] };
  }
  let parsed;
  try {
    parsed = JSON.parse(readRel(root, MANIFEST_PATH));
  } catch (err) {
    return {
      catalog: null,
      checks: null,
      problems: [`${MANIFEST_PATH}: not valid JSON (${err.message})`],
    };
  }
  const { checks, problems: shape } = validateManifest(parsed);
  problems.push(...shape.map((p) => `${MANIFEST_PATH}: ${p}`));
  if (!checks) return { catalog: null, checks: null, problems };

  // Check files: exactly one per manifest ID, nothing else named MT-*.sql.
  const checkFiles = new Set(
    listDir(abs(CATALOG_DIR))
      .filter((d) => d.isFile())
      .map((d) => d.name),
  );
  const wanted = new Set(checks.map((c) => `${c.id}.sql`));
  const catalog = [];
  const texts = [];
  for (const c of checks) {
    const rel = `${CATALOG_DIR}/${c.id}.sql`;
    let sql = null;
    if (!checkFiles.has(`${c.id}.sql`)) {
      problems.push(`${rel}: missing (manifest.json lists ${c.id})`);
    } else {
      const text = readRel(root, rel);
      const p = checkFileProblems(text);
      problems.push(...p.map((x) => `${rel}: ${x}`));
      sql = embeddedCheck(text);
      texts.push({ rel, id: c.id, text });
    }
    catalog.push({ id: c.id, sql, branches: [] });
  }
  for (const name of [...checkFiles].sort()) {
    if (/^mt-.*\.sql$/i.test(name) && !wanted.has(name)) {
      problems.push(`${CATALOG_DIR}/${name}: not listed in manifest.json`);
    }
  }

  // Copied text (catalog review D9): shared blocks across checks, and hand-kept copies in tests.
  problems.push(...sharedBlockProblems(texts));
  problems.push(...checkCopyProblems(root, new Map(catalog.map((c) => [c.id, c.sql]))));

  // Fixtures: exactly one per reachable branch, nothing else in fixtures/.
  const fixtureEntries = listDir(abs(FIXTURES_DIR));
  const fixtureFiles = new Set(fixtureEntries.filter((d) => d.isFile()).map((d) => d.name));
  const expected = new Set();
  checks.forEach((c, k) => {
    for (const b of c.branches) {
      if (b.unreachable !== null) {
        catalog[k].branches.push({ id: b.id, unreachable: b.unreachable, fixture: null });
        continue;
      }
      const name = fixtureName(c.id, b.id);
      const rel = `${FIXTURES_DIR}/${name}`;
      expected.add(name);
      let fixture = null;
      if (!fixtureFiles.has(name)) {
        problems.push(`${rel}: missing (positive control for ${c.id}.${b.id})`);
      } else {
        const text = readRel(root, rel);
        problems.push(...fixtureProblems(text).map((x) => `${rel}: ${x}`));
        fixture = toLf(text).replace(/^﻿/, '').trim();
      }
      catalog[k].branches.push({ id: b.id, unreachable: null, fixture });
    }
  });
  for (const d of [...fixtureEntries].sort((a, b) => a.name.localeCompare(b.name))) {
    if (d.isFile() && expected.has(d.name)) continue;
    problems.push(
      `${FIXTURES_DIR}/${d.name}: stray fixture (not the positive control of a reachable branch in manifest.json)`,
    );
  }
  return { catalog: problems.length === 0 ? catalog : null, checks, problems };
}

/** Number of assertions: one `clean` per check plus one `fires` per reachable branch. */
export function assertionCount(catalog) {
  return catalog.reduce(
    (n, c) => n + 1 + c.branches.filter((b) => b.unreachable === null).length,
    0,
  );
}

/** The generated pgTAP file (LF, ends with a newline). */
export function generate(catalog) {
  const out = [HEADER, 'begin;', `select plan(${assertionCount(catalog)});`];
  for (const c of catalog) {
    out.push(`-- ${c.id}`, 'select is_empty($q$', c.sql, `$q$, '${c.id}: clean');`);
    for (const b of c.branches) {
      if (b.unreachable !== null) continue;
      out.push(
        'savepoint mt;',
        b.fixture,
        'reset role;',
        'select isnt_empty($q$',
        'select * from (',
        c.sql,
        `) as v where v.branch = '${b.id}'`,
        `$q$, '${c.id}.${b.id}: fires');`,
        'rollback to savepoint mt;',
      );
    }
  }
  out.push('select * from finish();', 'rollback;');
  return out.join('\n') + '\n';
}

/** A floor file's value: a single non-negative integer line, else null. */
export function parseFloor(text) {
  const m = /^(\d+)(?:\r?\n)?$/.exec(text);
  if (!m) return null;
  const v = Number(m[1]);
  return Number.isSafeInteger(v) ? v : null;
}

function git(root, args) {
  const r = spawnSync('git', args, { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  return { ok: !r.error && r.status === 0, status: r.status, out: r.stdout ?? '' };
}

/** File content at a commit, or null when the path does not exist there. */
function showAt(root, sha, rel) {
  if (!git(root, ['cat-file', '-e', `${sha}:${rel}`]).ok) return null;
  const r = git(root, ['cat-file', 'blob', `${sha}:${rel}`]);
  if (!r.ok) throw new Error(`git cat-file blob ${sha}:${rel} failed`);
  return r.out;
}

/** The base tip plus every m*-reviewed tag that is an ancestor of HEAD. */
function refsToCompare(root, base, baseSha) {
  const refs = [{ label: `base ${base}`, sha: baseSha }];
  const tags = git(root, ['tag', '--list', 'm*-reviewed']);
  if (!tags.ok) throw new Error('git tag --list failed');
  for (const tag of tags.out
    .split('\n')
    .map((t) => t.trim())
    .filter(Boolean)
    .sort()) {
    const anc = spawnSync('git', ['merge-base', '--is-ancestor', `${tag}^{commit}`, 'HEAD'], {
      cwd: root,
    });
    if (anc.status === 1) continue;
    if (anc.status !== 0) throw new Error(`git merge-base --is-ancestor ${tag} HEAD failed`);
    const sha = git(root, ['rev-parse', `${tag}^{commit}`]).out.trim();
    refs.push({ label: `tag ${tag}`, sha });
  }
  return refs;
}

/**
 * --check rules that look at history: floors only go up, and the manifest only grows.
 * `checks` is the current validated manifest (null when it is invalid: the subset check is skipped).
 */
export function checkHistory({ root, base, checks }) {
  const resolved = git(root, ['rev-parse', '--verify', '--quiet', `${base}^{commit}`]);
  if (!resolved.ok) {
    return [
      `base ref "${base}" does not resolve (create it, e.g. \`git branch main origin/main\`, or pass --base)`,
    ];
  }
  const problems = [];
  const refs = refsToCompare(root, base, resolved.out.trim());

  for (const rel of FLOOR_FILES) {
    const abs = path.join(root, ...rel.split('/'));
    if (!existsSync(abs)) {
      problems.push(`${rel}: missing`);
      continue;
    }
    const current = parseFloor(readFileSync(abs, 'utf8'));
    if (current === null) {
      problems.push(`${rel}: must be a single non-negative integer line`);
      continue;
    }
    for (const ref of refs) {
      const text = showAt(root, ref.sha, rel);
      const then = text === null ? 0 : parseFloor(text);
      if (then === null) {
        problems.push(`${rel}: the file at ${ref.label} is not a single non-negative integer`);
      } else if (current < then) {
        problems.push(
          `${rel}: ${current} is lower than ${then} at ${ref.label} (floors only go up)`,
        );
      }
    }
  }

  if (checks) {
    const now = new Map(checks.map((c) => [c.id, new Map(c.branches.map((b) => [b.id, b]))]));
    for (const ref of refs) {
      const text = showAt(root, ref.sha, MANIFEST_PATH);
      if (text === null) continue; // a manifest missing there counts as empty
      let old;
      try {
        old = validateManifest(JSON.parse(text)).checks;
      } catch {
        old = null;
      }
      if (!old) {
        problems.push(`${MANIFEST_PATH}: the manifest at ${ref.label} is not valid`);
        continue;
      }
      for (const c of old) {
        const branches = now.get(c.id);
        if (!branches) {
          problems.push(
            `${MANIFEST_PATH}: ${c.id} (listed at ${ref.label}) was removed; IDs and branches may only be added`,
          );
          continue;
        }
        for (const b of c.branches) {
          const cur = branches.get(b.id);
          if (!cur) {
            problems.push(
              `${MANIFEST_PATH}: ${c.id}.${b.id} (listed at ${ref.label}) was removed; IDs and branches may only be added`,
            );
          } else if (cur.unreachable !== null && b.unreachable === null) {
            problems.push(
              `${MANIFEST_PATH}: ${c.id}.${b.id} is marked unreachable but is reachable at ${ref.label}`,
            );
          }
        }
      }
    }
  }
  return problems;
}

/**
 * Validates, then writes (default) or verifies (`check: true`) the generated file.
 * @returns {{ ok: boolean, problems: string[], count: number | null, wrote: boolean }}
 */
export function genCatalogTests({ root, check = false, base = 'main' }) {
  const { catalog, checks, problems } = loadCatalog(root);
  const count = catalog ? assertionCount(catalog) : null;
  const text = catalog ? generate(catalog) : null;
  let wrote = false;
  if (check) {
    if (text !== null) {
      const out = path.join(root, ...OUTPUT.split('/'));
      if (!existsSync(out)) problems.push(`${OUTPUT}: missing; ${REGEN}`);
      else if (toLf(readFileSync(out, 'utf8')) !== text) {
        problems.push(`${OUTPUT}: stale (differs from what the catalog generates); ${REGEN}`);
      }
    }
    problems.push(...checkHistory({ root, base, checks }));
  } else if (text !== null && problems.length === 0) {
    const out = path.join(root, ...OUTPUT.split('/'));
    mkdirSync(path.dirname(out), { recursive: true });
    writeFileSync(out, text);
    wrote = true;
  }
  return { ok: problems.length === 0, problems, count, wrote };
}

/** CLI body; returns the exit code. */
export function main({ argv, env, root, log = console.log, error = console.error }) {
  const known = argv.every(
    (a, i) =>
      a === '--check' ||
      a === '--base' ||
      a.startsWith('--base=') ||
      (argv[i - 1] === '--base' && !a.startsWith('--')),
  );
  if (!known) {
    error('usage: node scripts/gen-catalog-tests.mjs [--check] [--base <ref>]');
    return 2;
  }
  const check = argv.includes('--check');
  let base;
  try {
    base = resolveBase(argv, env);
  } catch (err) {
    error(`gen-catalog-tests: ${err.message}`);
    return 2;
  }
  let result;
  try {
    result = genCatalogTests({ root, check, base });
  } catch (err) {
    error(`gen-catalog-tests: ${err.message}`);
    return 1;
  }
  for (const p of result.problems) error(`gen-catalog-tests: ${p}`);
  if (!result.ok) {
    error(`gen-catalog-tests: ${result.problems.length} problem(s) (spec §8.5)`);
    return 1;
  }
  log(
    check
      ? `gen-catalog-tests: OK (${result.count} assertions)`
      : `gen-catalog-tests: wrote ${OUTPUT} (${result.count} assertions)`,
  );
  return 0;
}

if (isEntryPoint(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  process.exitCode = main({ argv: process.argv.slice(2), env: process.env, root });
}
