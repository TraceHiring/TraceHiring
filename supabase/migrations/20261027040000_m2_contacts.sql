-- Shared insert-once trigger (R5-52 c): rows of these tables are never changed, by any role, the owner included.
create function private.m2_insert_once()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  raise exception 'TRACE_GUARD: % are insert-once', replace(tg_table_name, '_', ' ') using errcode = '42501';
end
$$;
revoke execute on function private.m2_insert_once() from public, anon, authenticated, service_role;

-- ---------------------------------------------------------------------------------------------
-- org_keys (M2-3): one wrapped data key per org, purpose and version. Worker-only pattern (ADR-029): no app-role grant.
-- ---------------------------------------------------------------------------------------------
create table public.org_keys (
  org_id uuid not null references public.orgs (id) on delete restrict,
  purpose text not null check (purpose in ('contacts', 'bidx')),
  key_version int not null check (key_version >= 1),
  kms_key_ref text not null check (
    char_length(kms_key_ref) <= 256
    and kms_key_ref ~ '^(arn:aws:kms:ap-south-1:[0-9]{12}:(key|alias)/[A-Za-z0-9/_-]{1,200}|dev:[0-9]{1,9})$'
  ),
  wrapped_dek text not null check (char_length(wrapped_dek) between 16 and 1024 and wrapped_dek ~ '^[A-Za-z0-9+/]+={0,2}$'),
  created_at timestamptz not null default now(),
  retired_at timestamptz null,
  primary key (org_id, purpose, key_version)
);
alter table public.org_keys enable row level security;
-- R2-15: the first use inserts version 1 with `on conflict do nothing` and re-selects, so racing callers share one key.
grant select on public.org_keys to trace_api, trace_messaging_worker;
grant insert (org_id, purpose, key_version, kms_key_ref, wrapped_dek) on public.org_keys to trace_api;
create policy org_keys_select_api on public.org_keys for select to trace_api
  using (org_id = (select private.api_org_id()));
create policy org_keys_insert_api on public.org_keys for insert to trace_api
  with check (org_id = (select private.api_org_id()));
create policy org_keys_select_messaging_worker on public.org_keys for select to trace_messaging_worker
  using (org_id = (select private.job_org_id()));

-- ---------------------------------------------------------------------------------------------
-- candidates (R2-1, R2-2): one row per person per workspace, keyed by the blind-index fingerprint of the normalised
-- email. No DOB, age, adult flag, gender, college or free text (the adult answers stay on invitations, D1).
-- ---------------------------------------------------------------------------------------------
create table public.candidates (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.orgs (id) on delete restrict,
  workspace_id uuid not null,
  full_name_ct text not null check (char_length(full_name_ct) <= 2048 and full_name_ct ~ '^v1\.[0-9]+\.[A-Za-z0-9_-]+$'),
  key_version int not null check (key_version >= 1),
  contact_fingerprint text not null check (contact_fingerprint ~ '^[0-9a-f]{64}$'),
  created_by uuid null,
  created_at timestamptz not null default now(),
  unique (org_id, id),
  unique (org_id, id, workspace_id),
  unique (org_id, workspace_id, contact_fingerprint),
  foreign key (org_id, workspace_id) references public.workspaces (org_id, id) on delete restrict
);
alter table public.candidates enable row level security;

-- BEFORE INSERT: only the operator path names the creator (the tests_guard pattern).
create function private.candidates_label()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  new.created_by := case when private.is_operator() then new.created_by else (select auth.uid()) end;
  new.created_at := now();
  return new;
end
$$;
revoke execute on function private.candidates_label() from public, anon, authenticated, service_role;
create trigger candidates_label before insert on public.candidates
  for each row execute function private.candidates_label();
create trigger candidates_insert_once before update on public.candidates
  for each row execute function private.m2_insert_once();
alter table public.candidates enable always trigger candidates_label;
alter table public.candidates enable always trigger candidates_insert_once;

-- Staff of the workspace read and insert (ingest_invite_batch runs as the caller, R5-15); no UPDATE or DELETE grant.
grant select on public.candidates to authenticated;
grant insert (org_id, workspace_id, full_name_ct, key_version, contact_fingerprint) on public.candidates to authenticated;
create policy candidates_select_staff on public.candidates for select to authenticated
  using (workspace_id = any ((select private.my_workspace_ids('{org_owner,admin,recruiter}'))::uuid[]));
create policy candidates_insert_staff on public.candidates for insert to authenticated
  with check (workspace_id = any ((select private.my_workspace_ids('{org_owner,admin,recruiter}'))::uuid[]));

-- ---------------------------------------------------------------------------------------------
-- candidate_contacts (M2-3, R5-4): ciphertext, blind indexes and display hints; insert-once (R5-52 c).
-- ---------------------------------------------------------------------------------------------
create table public.candidate_contacts (
  org_id uuid not null references public.orgs (id) on delete restrict,
  candidate_id uuid not null,
  workspace_id uuid not null,
  email_ct text not null check (char_length(email_ct) <= 2048 and email_ct ~ '^v1\.[0-9]+\.[A-Za-z0-9_-]+$'),
  phone_ct text null check (phone_ct is null or (char_length(phone_ct) <= 2048 and phone_ct ~ '^v1\.[0-9]+\.[A-Za-z0-9_-]+$')),
  email_bidx text not null check (email_bidx ~ '^[0-9a-f]{64}$'),
  phone_bidx text null check (phone_bidx is null or phone_bidx ~ '^[0-9a-f]{64}$'),
  email_hint text not null check (char_length(email_hint) <= 80 and email_hint ~ '^[a-z0-9]•••@[a-z0-9.-]+$'),
  phone_hint text null check (phone_hint is null or phone_hint ~ '^••••[0-9]{4}$'),
  key_version int not null check (key_version >= 1),
  created_at timestamptz not null default now(),
  primary key (org_id, candidate_id),
  foreign key (org_id, candidate_id, workspace_id) references public.candidates (org_id, id, workspace_id) on delete restrict,
  check ((phone_ct is null) = (phone_bidx is null) and (phone_ct is null) = (phone_hint is null))
);
create index candidate_contacts_workspace_idx on public.candidate_contacts (org_id, workspace_id);
alter table public.candidate_contacts enable row level security;
create trigger candidate_contacts_insert_once before update on public.candidate_contacts
  for each row execute function private.m2_insert_once();
alter table public.candidate_contacts enable always trigger candidate_contacts_insert_once;
grant select on public.candidate_contacts to authenticated;
grant insert (org_id, candidate_id, workspace_id, email_ct, phone_ct, email_bidx, phone_bidx, email_hint, phone_hint,
  key_version) on public.candidate_contacts to authenticated;
create policy candidate_contacts_select_staff on public.candidate_contacts for select to authenticated
  using (workspace_id = any ((select private.my_workspace_ids('{org_owner,admin,recruiter}'))::uuid[]));
create policy candidate_contacts_insert_staff on public.candidate_contacts for insert to authenticated
  with check (workspace_id = any ((select private.my_workspace_ids('{org_owner,admin,recruiter}'))::uuid[]));
