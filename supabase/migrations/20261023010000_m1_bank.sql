-- item_variants ----------------------------------------------------------------------------------
create function private.item_variants_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_org uuid := case when tg_op = 'DELETE' then old.org_id else new.org_id end;
  v_parent uuid := case when tg_op = 'DELETE' then old.item_version_id else new.item_version_id end;
  v_section uuid;
  v_status public.item_status;
  v_param boolean;
  v_diff numeric;
  v_ws uuid;
begin
  if tg_op = 'UPDATE' then
    raise exception 'TRACE_GUARD: variants are immutable' using errcode = '42501';
  end if;
  select i.section_id, i.status, i.is_parameterised, i.difficulty, i.workspace_id
    into v_section, v_status, v_param, v_diff, v_ws
  from public.item_versions as i where i.org_id = v_org and i.id = v_parent for share;
  if not found then
    raise exception 'TRACE_GUARD: item version not found' using errcode = '23503';
  end if;
  -- R2-22, R3-4: variants are written and regenerated only while their bank version is a draft.
  if v_section is not null or not v_param or v_status <> 'draft' then
    raise exception 'TRACE_GUARD: variants change only while their parameterised item is a draft' using errcode = '42501';
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;
  new.workspace_id := v_ws;
  -- ABH-7: a variant's difficulty is the item's unless the author sets one within 0.10 of it.
  if v_diff is null then
    raise exception 'TRACE_GUARD: set the item difficulty before its variants' using errcode = '42501';
  end if;
  if abs(new.difficulty - v_diff) > 0.10 then
    raise exception 'TRACE_GUARD: a variant difficulty must be within 0.10 of its item' using errcode = '23514';
  end if;
  return new;
end
$$;
revoke execute on function private.item_variants_guard() from public, anon, authenticated, service_role;
