create or replace function private.item_versions_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_status public.test_version_status;
  v_tv uuid;
  v_test uuid;
  v_ws uuid;
  v_item_ws uuid;
  v_item_format public.section_format;
  v_item_skill text;
  v_role text := current_setting('role');
  v_op boolean := private.is_operator();
  v_uid uuid := (select auth.uid());
  v_lib uuid := private.library_org_id();
  v_content boolean;
  v_approval boolean;
begin
  -- ===== Inline rows: D1's path (20261014065417_d1_authoring.sql), unchanged in substance ==========================
  if (tg_op = 'INSERT' and new.section_id is not null) or (tg_op <> 'INSERT' and old.section_id is not null) then
    if tg_op = 'INSERT' then
      select s.test_version_id, s.test_id, s.workspace_id into v_tv, v_test, v_ws
      from public.sections as s where s.org_id = new.org_id and s.id = new.section_id for share;
      if not found then
        raise exception 'TRACE_GUARD: section not found' using errcode = '23503';
      end if;
      select v.status into v_status
      from public.test_versions as v where v.org_id = new.org_id and v.id = v_tv for share;
      if v_status <> 'draft' then
        raise exception 'TRACE_GUARD: the test version is frozen' using errcode = '42501';
      end if;
      new.test_version_id := v_tv;
      new.test_id := v_test;
      new.workspace_id := v_ws;
      new.created_by := (select auth.uid());
      if new.rubric_version_id is not null then
        perform 1 from public.rubric_versions as r
          where r.org_id = new.org_id and r.id = new.rubric_version_id for share;
      end if;
      -- M1: an inline item is human-written and published by its author (R2-1). A value outside the origin CHECK is
      -- left for the CHECK to refuse (23514, rls_d1_tests); any value inside it is the editor's 'human' (carried n-3).
      if not v_op and new.origin in ('human', 'import', 'ai_draft', 'library') then
        new.origin := 'human';
      end if;
      if new.ai_draft_job_id is not null or new.import_job_id is not null or new.source_item_version_id is not null
        or new.is_parameterised then
        raise exception 'TRACE_GUARD: an inline item has no bank provenance or variants' using errcode = '42501';
      end if;
      if exists (select 1 from public.items as i where i.org_id = new.org_id and i.id = new.item_id) then
        raise exception 'TRACE_GUARD: an inline item cannot take a bank item identity' using errcode = '42501';
      end if;
      new.status := 'approved';
      new.approved_by := null;
      new.approved_at := null;
      new.reviewed_by := null;
      new.key_reviewed_by := null;
      return new;
    end if;

    select v.status into v_status
    from public.test_versions as v where v.org_id = old.org_id and v.id = old.test_version_id for share;
    if v_status <> 'draft' then
      raise exception 'TRACE_GUARD: the test version is frozen' using errcode = '42501';
    end if;
    if tg_op = 'DELETE' then
      return old;
    end if;
    if new.id is distinct from old.id or new.org_id is distinct from old.org_id
      or new.workspace_id is distinct from old.workspace_id or new.test_id is distinct from old.test_id
      or new.test_version_id is distinct from old.test_version_id or new.section_id is distinct from old.section_id
      or new.format is distinct from old.format or new.item_id is distinct from old.item_id
      or new.version_no is distinct from old.version_no or new.origin is distinct from old.origin
      or new.created_by is distinct from old.created_by or new.created_at is distinct from old.created_at then
      raise exception 'TRACE_GUARD: item id, org, scope, section, format and identity are immutable'
        using errcode = '42501';
    end if;
    if new.status is distinct from old.status or new.is_parameterised is distinct from old.is_parameterised
      or new.param_spec is distinct from old.param_spec or new.language is distinct from old.language
      or new.key_reviewed_by is distinct from old.key_reviewed_by or new.approved_by is distinct from old.approved_by
      or new.approved_at is distinct from old.approved_at or new.reviewed_by is distinct from old.reviewed_by
      or new.ai_draft_job_id is distinct from old.ai_draft_job_id or new.import_job_id is distinct from old.import_job_id
      or new.import_row_no is distinct from old.import_row_no
      or new.source_item_version_id is distinct from old.source_item_version_id then
      raise exception 'TRACE_GUARD: an inline item has no review state, variants or provenance' using errcode = '42501';
    end if;
    if new.rubric_version_id is not null and new.rubric_version_id is distinct from old.rubric_version_id then
      perform 1 from public.rubric_versions as r
        where r.org_id = new.org_id and r.id = new.rubric_version_id for share;
    end if;
    return new;
  end if;

  -- ===== Bank rows (section_id null): §4.1 ==========================================================================
  if tg_op = 'INSERT' then
    if not v_op and v_role not in ('authenticated', 'trace_authoring_worker') then
      raise exception 'TRACE_GUARD: bank items are written by org users and the authoring worker only'
        using errcode = '42501';
    end if;
    -- The items row is locked: version numbers are assigned in order and the item cannot be deleted meanwhile.
    select i.workspace_id, i.format, i.skill_key into v_item_ws, v_item_format, v_item_skill
    from public.items as i where i.org_id = new.org_id and i.id = new.item_id for no key update;
    if not found then
      raise exception 'TRACE_GUARD: item not found' using errcode = '23503';
    end if;
    if new.format is distinct from v_item_format then
      raise exception 'TRACE_GUARD: the version format differs from its item' using errcode = '42501';
    end if;
    new.workspace_id := v_item_ws;
    new.skill_key := coalesce(new.skill_key, v_item_skill);
    if not private.skill_key_exists(new.skill_key) then
      raise exception 'TRACE_GUARD: skill not found' using errcode = '23503';
    end if;
    select coalesce(max(v.version_no), 0) + 1 into new.version_no
    from public.item_versions as v where v.org_id = new.org_id and v.item_id = new.item_id and v.section_id is null;
    -- The origin comes from the write path (carried n-3); a value outside the CHECK is left for the CHECK.
    if not v_op and new.origin in ('human', 'import', 'ai_draft', 'library') then
      new.origin := case
        when v_role = 'trace_authoring_worker' then 'ai_draft'
        when new.source_item_version_id is not null then 'library'
        when new.import_job_id is not null then 'import'
        else 'human'
      end;
    end if;
    if new.origin = 'ai_draft' then
      if new.is_parameterised then
        raise exception 'TRACE_GUARD: an AI draft is not parameterised' using errcode = '42501';
      end if;
      -- R5-35: the authoring worker writes only for a running drafting job of the same org and workspace.
      if not v_op and not private.ai_draft_job_running(new.org_id, new.workspace_id, new.ai_draft_job_id) then
        raise exception 'TRACE_GUARD: an AI draft needs its running drafting job' using errcode = '42501';
      end if;
      new.status := 'in_review';
    else
      if new.ai_draft_job_id is not null then
        raise exception 'TRACE_GUARD: only an AI draft names a drafting job' using errcode = '42501';
      end if;
      new.status := 'draft';
    end if;
    if new.import_job_id is not null and not v_op
      and not private.import_job_open(new.org_id, new.workspace_id, new.import_job_id) then
      raise exception 'TRACE_GUARD: the import job is not open' using errcode = '42501';
    end if;
    if new.source_item_version_id is not null and not exists (
      select 1 from public.item_versions as s
      where s.org_id = v_lib and s.id = new.source_item_version_id and s.section_id is null and s.status = 'approved'
    ) then
      raise exception 'TRACE_GUARD: a library copy names an approved library item' using errcode = '42501';
    end if;
    new.approved_by := null;
    new.approved_at := null;
    new.reviewed_by := null;
    new.key_reviewed_by := null;
    new.created_by := case when v_op then new.created_by else v_uid end;
    new.created_at := now();
    if new.rubric_version_id is not null then
      perform 1 from public.rubric_versions as r
        where r.org_id = new.org_id and r.id = new.rubric_version_id for share;
    end if;
    return new;
  end if;

  if tg_op = 'DELETE' then
    if old.status <> 'draft' then
      raise exception 'TRACE_GUARD: only a draft item version can be deleted' using errcode = '42501';
    end if;
    return old;
  end if;

  -- UPDATE of a bank row.
  if new.id is distinct from old.id or new.org_id is distinct from old.org_id
    or new.workspace_id is distinct from old.workspace_id or new.test_id is distinct from old.test_id
    or new.test_version_id is distinct from old.test_version_id or new.section_id is distinct from old.section_id
    or new.position is distinct from old.position or new.format is distinct from old.format
    or new.item_id is distinct from old.item_id or new.version_no is distinct from old.version_no
    or new.origin is distinct from old.origin or new.created_by is distinct from old.created_by
    or new.created_at is distinct from old.created_at or new.ai_draft_job_id is distinct from old.ai_draft_job_id
    or new.import_job_id is distinct from old.import_job_id or new.import_row_no is distinct from old.import_row_no
    or new.source_item_version_id is distinct from old.source_item_version_id then
    raise exception 'TRACE_GUARD: item version identity and provenance are immutable' using errcode = '42501';
  end if;
  v_content := new.stem is distinct from old.stem or new.options is distinct from old.options
    or new.rubric_version_id is distinct from old.rubric_version_id or new.content_sha256 is distinct from old.content_sha256
    or new.skill_key is distinct from old.skill_key or new.difficulty is distinct from old.difficulty
    or new.language is distinct from old.language or new.is_parameterised is distinct from old.is_parameterised
    or new.param_spec is distinct from old.param_spec or new.media is distinct from old.media;
  v_approval := new.approved_by is distinct from old.approved_by or new.approved_at is distinct from old.approved_at
    or new.reviewed_by is distinct from old.reviewed_by or new.key_reviewed_by is distinct from old.key_reviewed_by;

  if new.status = old.status then
    -- I-M1-3: content is immutable once a version leaves draft; an edit is a new version (Q23).
    if old.status <> 'draft' and (v_content or v_approval) then
      raise exception 'TRACE_GUARD: an item version is frozen once it leaves draft' using errcode = '42501';
    end if;
    if v_approval and not v_op then
      raise exception 'TRACE_GUARD: approval columns are set by the approval only' using errcode = '42501';
    end if;
    if new.skill_key is distinct from old.skill_key and not private.skill_key_exists(new.skill_key) then
      raise exception 'TRACE_GUARD: skill not found' using errcode = '23503';
    end if;
    if new.rubric_version_id is not null and new.rubric_version_id is distinct from old.rubric_version_id then
      perform 1 from public.rubric_versions as r
        where r.org_id = new.org_id and r.id = new.rubric_version_id for share;
    end if;
    return new;
  end if;

  if v_content then
    raise exception 'TRACE_GUARD: content and status change in separate updates' using errcode = '42501';
  end if;

  if old.status = 'draft' and new.status = 'in_review' then
    if v_approval and not v_op then
      raise exception 'TRACE_GUARD: approval columns are set by the approval only' using errcode = '42501';
    end if;
    perform private.item_version_ready(new.org_id, new.id, new.format, new.is_parameterised, new.difficulty);
    return new;
  end if;

  if (old.status = 'in_review' and new.status in ('approved', 'not_approved'))
    or (old.status = 'draft' and new.status = 'approved' and old.origin in ('import', 'library')) then
    -- R5-37: library imports keep expert review; Q23: imports and library copies are approved by the importer / copier.
    if old.status = 'draft' and new.org_id = v_lib then
      raise exception 'TRACE_GUARD: a library item is approved by an expert review' using errcode = '42501';
    end if;
    -- M1-3, R5-38, R5-40: an approver is an owner, admin, recruiter or reviewer of the item's workspace whose membership
    -- counts at its aal. The policies check it too; the library copy trigger writes as the owner, so it is checked here.
    if not v_op and not (new.workspace_id = any (private.my_workspace_ids('{org_owner,admin,recruiter,reviewer}'))) then
      raise exception 'TRACE_GUARD: an approver role in the item workspace is required' using errcode = '42501';
    end if;
    if new.status = 'not_approved' then
      if v_approval and not v_op then
        raise exception 'TRACE_GUARD: approval columns are set by the approval only' using errcode = '42501';
      end if;
      return new;
    end if;
    perform private.item_version_ready(new.org_id, new.id, new.format, new.is_parameterised, new.difficulty);
    if not v_op then
      new.approved_by := v_uid;
      new.approved_at := now();
      if new.org_id = v_lib then
        new.reviewed_by := v_uid;
      else
        new.reviewed_by := null;
        new.key_reviewed_by := null;
      end if;
    else
      new.approved_at := coalesce(new.approved_at, now());
    end if;
    -- ABH-6 expert review in the library: the reviewer and the key reviewer are active library members other than the
    -- author.
    if new.org_id = v_lib then
      if new.reviewed_by is null or new.key_reviewed_by is null
        or new.reviewed_by is not distinct from old.created_by or new.key_reviewed_by is not distinct from old.created_by then
        raise exception 'TRACE_GUARD: a library item needs a reviewer and a key reviewer other than its author'
          using errcode = '42501';
      end if;
      if not exists (
        select 1 from public.memberships as m
        where m.org_id = v_lib and m.user_id = new.key_reviewed_by and m.status = 'active'
          and m.roles && '{org_owner,admin,recruiter,reviewer}'::public.org_role[]
      ) then
        raise exception 'TRACE_GUARD: the key reviewer is an active library member' using errcode = '42501';
      end if;
    end if;
    return new;
  end if;

  if old.status = 'approved' and new.status = 'retired' then
    if v_approval then
      raise exception 'TRACE_GUARD: an item version is frozen once it leaves draft' using errcode = '42501';
    end if;
    if not v_op and not (new.workspace_id = any (private.my_workspace_ids('{org_owner,admin,recruiter}'))) then
      raise exception 'TRACE_GUARD: retiring an item needs an owner, admin or recruiter' using errcode = '42501';
    end if;
    return new;
  end if;

  raise exception 'TRACE_GUARD: item status change not allowed' using errcode = '42501';
end
$$;
revoke execute on function private.item_versions_guard() from public, anon, authenticated, service_role;

-- Bank transitions are audited item.<verb> {item_version_id, from, to, self_approved} (§4.1; ids, enums, booleans only).
