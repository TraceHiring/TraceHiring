-- §5 ParamSpec, shape only (TypeScript in packages/item-variants is the one evaluator; SQL never evaluates, §3.4).
create function private.param_spec_valid(p_spec jsonb)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select coalesce(
    case
      when jsonb_typeof(p_spec) = 'object' and octet_length(p_spec::text) <= 16384 then
        not exists (
          select 1 from jsonb_object_keys(p_spec) as k
          where k not in ('params', 'derived', 'constraints', 'stem', 'options', 'correctOptionId', 'count')
        )
        and jsonb_typeof(p_spec -> 'params') = 'object'
        and (select count(*) from jsonb_object_keys(p_spec -> 'params')) between 1 and 8
        and not exists (
          select 1 from jsonb_each(p_spec -> 'params') as e
          where e.key !~ '^[a-z][a-z0-9_]{0,15}$'
            or jsonb_typeof(e.value) is distinct from 'object'
            or e.value ->> 'kind' is null
            or e.value ->> 'kind' not in ('int', 'choice')
            or (e.value ->> 'kind' = 'int' and (
              jsonb_typeof(e.value -> 'min') is distinct from 'number'
              or jsonb_typeof(e.value -> 'max') is distinct from 'number'
              or jsonb_typeof(e.value -> 'step') is distinct from 'number'))
            or (e.value ->> 'kind' = 'choice' and (
              jsonb_typeof(e.value -> 'values') is distinct from 'array'
              or jsonb_array_length(e.value -> 'values') not between 1 and 20))
        )
        and (not (p_spec ? 'derived') or (
          jsonb_typeof(p_spec -> 'derived') = 'object'
          and (select count(*) from jsonb_object_keys(p_spec -> 'derived')) <= 8
          and not exists (
            select 1 from jsonb_each(p_spec -> 'derived') as e
            where e.key !~ '^[a-z][a-z0-9_]{0,15}$' or jsonb_typeof(e.value) is distinct from 'string'
              or char_length(e.value #>> '{}') not between 1 and 200
          )))
        and (not (p_spec ? 'constraints') or (
          jsonb_typeof(p_spec -> 'constraints') = 'array'
          and jsonb_array_length(p_spec -> 'constraints') <= 8
          and not exists (
            select 1 from jsonb_array_elements(p_spec -> 'constraints') as c
            where jsonb_typeof(c) is distinct from 'string' or char_length(c #>> '{}') not between 1 and 200
          )))
        and jsonb_typeof(p_spec -> 'stem') = 'string'
        and char_length(p_spec ->> 'stem') between 1 and 4000
        and jsonb_typeof(p_spec -> 'options') = 'array'
        and jsonb_array_length(p_spec -> 'options') between 2 and 6
        and not exists (
          select 1 from jsonb_array_elements(p_spec -> 'options') as o
          where jsonb_typeof(o -> 'id') is distinct from 'string' or jsonb_typeof(o -> 'text') is distinct from 'string'
        )
        and jsonb_typeof(p_spec -> 'correctOptionId') = 'string'
        and exists (
          select 1 from jsonb_array_elements(p_spec -> 'options') as o where o ->> 'id' = p_spec ->> 'correctOptionId'
        )
        and jsonb_typeof(p_spec -> 'count') = 'number'
        and (p_spec ->> 'count')::numeric between 5 and 200
      else false
    end,
    false
  )
$$;
revoke execute on function private.param_spec_valid(jsonb) from public, anon, authenticated, service_role;
grant execute on function private.param_spec_valid(jsonb) to authenticated, trace_authoring_worker;

-- §5 ItemMedia: 1-4 refs {key, alt}; the key is content-addressed under the org's item-media prefix (§6.9).
create function private.media_refs_valid(p_media jsonb)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select coalesce(
    case
      when jsonb_typeof(p_media) = 'array' and jsonb_array_length(p_media) between 1 and 4 then
        not exists (
          select 1 from jsonb_array_elements(p_media) as m
          where jsonb_typeof(m) is distinct from 'object'
            or (select array_agg(k order by k) from jsonb_object_keys(m) as k) is distinct from array['alt', 'key']::text[]
            or jsonb_typeof(m -> 'key') is distinct from 'string'
            or (m ->> 'key') !~ '^item-media/[0-9a-f-]{36}/[0-9a-f]{64}\.(png|jpg|webp)$'
            or jsonb_typeof(m -> 'alt') is distinct from 'string'
            or char_length(m ->> 'alt') not between 1 and 300
        )
      else false
    end,
    false
  )
$$;
revoke execute on function private.media_refs_valid(jsonb) from public, anon, authenticated, service_role;
grant execute on function private.media_refs_valid(jsonb) to authenticated, trace_authoring_worker;

