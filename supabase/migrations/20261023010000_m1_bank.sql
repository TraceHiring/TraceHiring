-- item_answer_keys guard v2 (re-derived from 20261014065417_d1_authoring.sql, R5-30, R5-44) ----------------------------
create or replace function private.item_answer_keys_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_status public.test_version_status;
  v_tv uuid;
  v_test uuid;
  v_ws uuid;
  v_section uuid;
  v_options jsonb;
  v_item_status public.item_status;
  v_origin text;
  v_item uuid := case when tg_op = 'DELETE' then old.item_version_id else new.item_version_id end;
  v_org uuid := case when tg_op = 'DELETE' then old.org_id else new.org_id end;
begin
  select i.section_id, i.test_version_id, i.test_id, i.workspace_id, i.options, i.status, i.origin
    into v_section, v_tv, v_test, v_ws, v_options, v_item_status, v_origin
  from public.item_versions as i where i.org_id = v_org and i.id = v_item for share;
  if not found then
    raise exception 'TRACE_GUARD: item version not found' using errcode = '23503';
  end if;
  if v_section is not null then
    -- Inline item: D1's freeze on the test version (R3-11).
    select v.status into v_status
    from public.test_versions as v where v.org_id = v_org and v.id = v_tv for share;
    if v_status <> 'draft' then
      raise exception 'TRACE_GUARD: the test version is frozen' using errcode = '42501';
    end if;
    -- R5-44 (replaces D1 I-12's NOT NULL test_id): an inline key takes its test from its item.
    if v_test is null then
      raise exception 'TRACE_GUARD: an inline answer key needs its test' using errcode = '23514';
    end if;
  else
    -- Bank item: keys change only while the version is a draft; the authoring worker adds the key of its own
    -- in-review AI draft (§6.4).
    if not (v_item_status = 'draft'
      or (tg_op = 'INSERT' and current_setting('role') = 'trace_authoring_worker'
          and v_origin = 'ai_draft' and v_item_status = 'in_review')) then
      raise exception 'TRACE_GUARD: the item version is frozen' using errcode = '42501';
    end if;
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;
  if tg_op = 'INSERT' then
    new.test_id := v_test;
    new.workspace_id := v_ws;
    new.created_by := (select auth.uid());
  else
    if new.org_id is distinct from old.org_id or new.item_version_id is distinct from old.item_version_id
      or new.workspace_id is distinct from old.workspace_id or new.test_id is distinct from old.test_id
      or new.format is distinct from old.format or new.created_by is distinct from old.created_by
      or new.created_at is distinct from old.created_at or new.library_sourced is distinct from old.library_sourced then
      raise exception 'TRACE_GUARD: answer key org, item and scope are immutable' using errcode = '42501';
    end if;
  end if;
  if jsonb_typeof(new.key) is distinct from 'object'
    or (select count(*) from jsonb_object_keys(new.key)) <> 1
    or jsonb_typeof(new.key -> 'option_id') is distinct from 'string'
    or not exists (
      select 1 from jsonb_array_elements(v_options) as o where o ->> 'id' = new.key ->> 'option_id'
    ) then
    raise exception 'TRACE_BAD_ANSWER_KEY' using errcode = '23514';
  end if;
  return new;
end
$$;
