create function private.items_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if not private.skill_key_exists(new.skill_key) then
      raise exception 'TRACE_GUARD: skill not found' using errcode = '23503';
    end if;
    new.created_by := case when private.is_operator() then new.created_by else (select auth.uid()) end;
    new.created_at := now();
    return new;
  end if;
  if tg_op = 'DELETE' then
    -- R3-8: an item is deleted only while it has no version (a version is deleted only while it is a draft).
    if exists (
      select 1 from public.item_versions as v
      where v.org_id = old.org_id and v.item_id = old.id and v.section_id is null
    ) then
      raise exception 'TRACE_GUARD: an item with versions cannot be deleted' using errcode = '42501';
    end if;
    return old;
  end if;
  if new.id is distinct from old.id or new.org_id is distinct from old.org_id
    or new.workspace_id is distinct from old.workspace_id or new.format is distinct from old.format
    or new.created_by is distinct from old.created_by or new.created_at is distinct from old.created_at then
    raise exception 'TRACE_GUARD: item id, org, workspace, format and creator are immutable' using errcode = '42501';
  end if;
  if new.skill_key is distinct from old.skill_key and not private.skill_key_exists(new.skill_key) then
    raise exception 'TRACE_GUARD: skill not found' using errcode = '23503';
  end if;
  return new;
end
$$;
