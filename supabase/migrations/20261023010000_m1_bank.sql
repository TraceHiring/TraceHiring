-- Stems and metadata of approved library items; never a key, never an option id (LibraryItemCard, §5).
create function private.library_browse(
  p_viewer uuid,
  p_aal text,
  p_amr text[],
  p_skill text,
  p_format public.section_format,
  p_difficulty_min numeric,
  p_difficulty_max numeric,
  p_after uuid,
  p_limit int
)
returns table (
  library_item_version_id uuid,
  format public.section_format,
